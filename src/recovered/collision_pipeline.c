static uint16_t read16(const uint8_t *data)
{
    return (uint16_t)((uint16_t)data[0] | ((uint16_t)data[1] << 8u));
}

/* Ensure the same underlying frame state crosses all recovered modules.
 * Fail before touching any live fighter, effect or workspace allocation. */
static bool validate(const stf_collision_pipeline_model2 *pipeline)
{
    const stf_collision_copro_area_model2 *area;
    const stf_collision_frame_model2 *frame;
    const stf_collision_combat_model2 *combat;
    unsigned i;

    if (pipeline == NULL || pipeline->area == NULL ||
        pipeline->frame == NULL || pipeline->combat == NULL) {
        return false;
    }
    area = pipeline->area;
    frame = pipeline->frame;
    combat = pipeline->combat;
    if (area->workspace == NULL || frame->workspace != area->workspace ||
        combat->workspace != area->workspace ||
        frame->workspace_size != area->workspace_size ||
        combat->workspace_size != area->workspace_size ||
        area->workspace_size < STF_COLLISION_ATTACK_WORKSPACE_MODEL2_MIN_SIZE ||
        area->workspace_size < STF_COLLISION_KIND_APPLY_WORKSPACE_MIN_SIZE ||
        area->geometry == NULL || area->rom_view == NULL ||
        frame->mapping == NULL ||
        frame->effect == NULL ||
        frame->effect_size < STF_COLLISION_ATTACK_EFFECT_MODEL2_SIZE ||
        frame->copro_hit_xyz == NULL ||
        frame->copro_hit_xyz_size < STF_COLLISION_ATTACK_EFFECT_XYZ_SIZE ||
        combat->effect == NULL || combat->attack_body == NULL ||
        (combat->guard_tail != NULL &&
         combat->normal_profile_table == NULL) ||
        (combat->guard_common_tail != NULL &&
         combat->normal_profile_table == NULL) ||
        (combat->normal_profile_table != NULL &&
         combat->normal_profile_table_size < STF_ATTACK_HIT_PROFILE_RECORD_SIZE) ||
        (combat->guard_vector_tgp != NULL && combat->guard_tail == NULL)) {
        return false;
    }
    for (i = 0u; i < 2u; ++i) {
        if (area->fighter[i] == NULL ||
            area->fighter[i] != frame->fighters[i] ||
            area->fighter[i] != combat->fighters[i] ||
            area->fighter_size[i] != frame->fighter_sizes[i] ||
            area->fighter_size[i] != combat->fighter_sizes[i] ||
            area->fighter_size[i] < STF_COLLISION_NO_UNIT_SELF_MIN_SIZE ||
            area->fighter_size[i] < STF_DAMAGE_UNIT_DEFENDER_MIN_SIZE ||
            area->fighter_size[i] < STF_COLLISION_ATTACK_FIGHTER_MODEL2_MIN_SIZE ||
            area->fighter_size[i] < STF_COPRO_ATTACK_FLAG_FIGHTER_MIN_SIZE ||
            area->fighter[i][4u] != i ||
            frame->r5_selected_xyz[i] == NULL ||
            frame->r5_selected_xyz_sizes[i] <
                STF_COLLISION_ATTACK_EFFECT_XYZ_SIZE ||
            combat->enemy_slots[i] == NULL ||
            combat->enemy_slot_sizes[i] <
                STF_ATTACK_HIT_ENEMY_MODEL2_MIN_SIZE) {
            return false;
        }
    }
    /* Prevent any malformed table/device configuration from resetting RAM.
     * The area stage performs detailed ROM-dependent validation itself. */
    if ((area->angle_lut != NULL &&
         (area->distance == NULL ||
          area->angle_lut_size < STF_COLLISION_AREA_ANGLE_LUT_COUNT)) ||
        ((area->table_2e250 != NULL || area->table_2e230 != NULL) &&
         (area->table_2e250 == NULL || area->table_2e230 == NULL ||
          area->angle_lut == NULL ||
          area->table_2e250_count < STF_COLLISION_AREA_TABLE_2E250_COUNT ||
          area->table_2e230_count < STF_COLLISION_AREA_TABLE_2E230_COUNT)) ||
        (area->kind_profiles != NULL &&
         area->kind_profile_count < STF_COLLISION_KIND_COUNT)) {
        return false;
    }
    return true;
}

bool stf_collision_pipeline_apply_model2(
    const stf_collision_pipeline_model2 *pipeline,
    stf_collision_pipeline_result *result
)
{
    stf_collision_pipeline_result local;
    const stf_collision_copro_area_model2 *area;
    unsigned i;

    if (!validate(pipeline) || result == NULL) {
        return false;
    }
    area = pipeline->area;
    memset(&local, 0, sizeof(local));
    if (!stf_collision_copro_area_stage_model2(area, &local.area)) {
        *result = local;
        return false;
    }
    local.completed_area = 1u;

    for (i = 0u; i < 2u; ++i) {
        const uint8_t other = (uint8_t)(1u - i);
        if (!stf_collision_no_unit_apply_model2(
                area->fighter[i], area->fighter_size[i],
                area->fighter[other], area->fighter_size[other],
                pipeline->stage_floor_bits,
                pipeline->stage_extent_bits,
                pipeline->no_coli_low_bits)) {
            *result = local;
            return false;
        }
        local.suppression_mask[i] = read16(area->fighter[i] + 0x6F8u);
        ++local.completed_suppressions;
    }

    /* The frame adapter reads +0xAC8 generated by calc_attack_flag;
     * no independent injected attack profile can go stale. */
    if (!stf_collision_frame_check_computed_model2(
            pipeline->frame, &local.frame)) {
        *result = local;
        return false;
    }
    local.completed_checks = true;

    if (!stf_collision_combat_apply_model2(
            pipeline->combat, &local.frame.order, &local.combat)) {
        *result = local;
        return false;
    }
    local.completed_combat = true;
    *result = local;
    return true;
}
